class Ord (Basis a) => ChainComplex a where
  type Basis a

  isBasis :: a -> Basis a -> Bool
  isBasis _ _ = True

  degree :: a -> Basis a -> Int
  diff :: a -> Morphism a a

-- | A chain complex with a known lower bound on the degrees of its basis
-- elements.
class ChainComplex a => BoundedBelow a where
  lowerBound :: a -> Int

-- | A non-negatively graded chain complex whose degree-zero group is
-- canonically generated by one element.
class BoundedBelow a => ConnectedChainComplex a

-- | A connected chain complex whose degree-one group is zero.
class ConnectedChainComplex a => OneReducedChainComplex a

type Chain a = Combination (Basis a)

instance ChainComplex () where
  type Basis () = ()
  degree _ _ = 0
  diff _ = morphismZeroOfDeg (-1)

instance BoundedBelow () where
  lowerBound _ = 0

instance ConnectedChainComplex ()

instance OneReducedChainComplex ()

class ChainComplex a => FiniteType a where
  dim :: a -> Int -> Int
  dim a i = length (basis a i)
  -- * `all isSimplex (basis n)`
  basis :: a -> Int -> [Basis a]

instance FiniteType () where
  dim _ 0 = 1
  dim _ _ = 0
  basis _ 0 = [()]
  basis _ _ = []

validComb :: ChainComplex a => a -> Chain a -> Bool
validComb a combination = and $ fmap (\(_, b) -> isBasis a b) (coeffs combination)

-- well, not really
kozulRule :: Num b => Int -> b -> b
kozulRule n c = if even n then c else negate c

-- | A homogeneous morphism between chain complexes.
data Morphism a b = Morphism
  { morphismDegree :: Int,
    onBasis :: Basis a -> Combination (Basis b)
  }

-- | Retag a morphism with unchanged endpoint basis types.
sameBasisMorphism ::
  (Basis a ~ Basis a', Basis b ~ Basis b') =>
  Morphism a b ->
  Morphism a' b'
sameBasisMorphism (Morphism morphismDegree action) =
  Morphism morphismDegree action

-- | Identity morphism between complexes with the same basis type.
sameBasisId ::
  Basis a ~ Basis b =>
  Morphism a b
sameBasisId = Morphism 0 singleComb

-- | Memoise a pure function for the lifetime of the returned closure.
--
-- The algorithms in this package build large morphisms out of recursive
-- contractions.  Those contractions describe DAGs, but evaluating them as
-- ordinary functions expands the DAG into a tree.  This helper lets the
-- recursive morphisms retain one result per visited basis element instead.
memoiseOrd :: Ord a => (a -> b) -> a -> b
memoiseOrd f = unsafePerformIO $ do
  cache <- newIORef Map.empty
  pure $ \key -> unsafePerformIO $ do
    current <- readIORef cache
    case Map.lookup key current of
      Just value -> pure value
      Nothing -> do
        value <- evaluate (f key)
        atomicModifyIORef' cache $ \latest ->
          case Map.insertLookupWithKey (\_ _ existing -> existing) key value latest of
            (Just existing, updated) -> (updated, existing)
            (Nothing, updated) -> (updated, value)
{-# NOINLINE memoiseOrd #-}

-- | Retain the image of each visited source basis element.
memoiseMorphism :: ChainComplex a => Morphism a b -> Morphism a b
memoiseMorphism (Morphism morphismDegree action) =
  Morphism morphismDegree (memoiseOrd action)

onComb :: ChainComplex b => Morphism a b -> Chain a -> Chain b
onComb m combination = bindCombination combination (m `onBasis`)

morphismZeroOfDeg :: Int -> Morphism a b
morphismZeroOfDeg d = Morphism d (const zeroCombination)

-- | Extend a function on basis representations to a degree-zero morphism.
basisMorphism ::
  (Basis a -> Basis b) ->
  Morphism a b
basisMorphism f = Morphism 0 (singleComb . f)

